def _setup_section(section):
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)


def _setup_base_style(doc):
    style = doc.styles['Normal']
    style.font.name = 'Times New Roman'
    style.font.size = Pt(14)
    pf = style.paragraph_format
    pf.line_spacing = 1.5
    pf.first_line_indent = Cm(1.25)

    for level, size in (('Heading 1', 16), ('Heading 2', 14)):
        s = doc.styles[level]
        s.font.name = 'Times New Roman'
        s.font.size = Pt(size)
        s.font.bold = True
        s.font.color.rgb = RGBColor(0x00, 0x00, 0x00)
        s.paragraph_format.first_line_indent = Cm(1.25)
        s.paragraph_format.line_spacing = 1.5
        s.paragraph_format.space_before = Pt(12)
        s.paragraph_format.space_after = Pt(6)


def add_para(doc, text, *, justify=True, first_indent=Cm(1.25)):
    p = doc.add_paragraph(text)
    if justify:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = first_indent
    return p


def add_ref(doc, n, text):
    """Добавляет нумерованную библиографическую запись (hanging indent)."""
    p = doc.add_paragraph(f'{n}. {text}')
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.left_indent = Cm(0.5)
    return p


