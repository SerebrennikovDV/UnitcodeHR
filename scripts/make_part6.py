def _setup_section(section):
    """Поля 3 / 1.5 / 2 / 2 см (лево/право/верх/низ), формат A4."""
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)


def _setup_base_style(doc):
    """Times New Roman 14, межстрочный 1.5, отступ первой строки 1.25 см."""
    style = doc.styles['Normal']
    style.font.name = 'Times New Roman'
    style.font.size = Pt(14)
    pf = style.paragraph_format
    pf.line_spacing = 1.5
    pf.first_line_indent = Cm(1.25)
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)

    for level, size in (('Heading 1', 16), ('Heading 2', 14), ('Heading 3', 14)):
        s = doc.styles[level]
        s.font.name = 'Times New Roman'
        s.font.size = Pt(size)
        s.font.bold = True
        s.font.color.rgb = RGBColor(0x00, 0x00, 0x00)
        s.paragraph_format.first_line_indent = Cm(1.25)
        s.paragraph_format.line_spacing = 1.5
        s.paragraph_format.space_before = Pt(12)
        s.paragraph_format.space_after = Pt(6)


def add_heading(doc, text, level=2):
    p = doc.add_heading(text, level=level)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    return p


def add_para(doc, text, *, justify=True):
    p = doc.add_paragraph(text)
    if justify:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    return p


def add_bullets(doc, items):
    for item in items:
        p = doc.add_paragraph(item, style='List Bullet')
        p.paragraph_format.first_line_indent = Cm(0)


def add_image(doc, path: Path, caption: str, width_cm: float = 15.5):
    if not path.exists():
        add_para(doc, f'[Изображение не найдено: {path.name}]')
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    run.add_picture(str(path), width=Cm(width_cm))
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.first_line_indent = Cm(0)
    for r in cap.runs:
        r.italic = True


def add_code_block(doc, code: str, caption: str | None = None):
    if caption:
        cap = doc.add_paragraph(caption)
        cap.paragraph_format.first_line_indent = Cm(0)
        for r in cap.runs:
            r.italic = True
    for line in code.split('\n'):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.left_indent = Cm(0.5)
        p.paragraph_format.line_spacing = 1.0
        run = p.add_run(line if line else ' ')
        run.font.name = 'Consolas'
        run.font.size = Pt(10)


def _set_cell_borders(cell):
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_borders = OxmlElement('w:tcBorders')
    for side in ('top', 'left', 'bottom', 'right'):
        b = OxmlElement(f'w:{side}')
        b.set(qn('w:val'), 'single')
        b.set(qn('w:sz'), '4')
        b.set(qn('w:space'), '0')
        b.set(qn('w:color'), '000000')
        tc_borders.append(b)
    tc_pr.append(tc_borders)


def add_table(doc, headers: list[str], rows: list[list[str]], col_widths_cm: list[float] | None = None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for idx, h in enumerate(headers):
        cell = table.rows[0].cells[idx]
        cell.text = ''
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        run = p.add_run(h)
        run.bold = True
        run.font.name = 'Times New Roman'
        run.font.size = Pt(12)
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        _set_cell_borders(cell)
        if col_widths_cm:
            cell.width = Cm(col_widths_cm[idx])

    for r_idx, row in enumerate(rows, start=1):
        for c_idx, value in enumerate(row):
            cell = table.rows[r_idx].cells[c_idx]
            cell.text = ''
            for line in value.split('\n'):
                p = cell.add_paragraph(line)
                p.paragraph_format.first_line_indent = Cm(0)
                p.paragraph_format.line_spacing = 1.15
                for run in p.runs:
                    run.font.name = 'Times New Roman'
                    run.font.size = Pt(12)
            # удалить пустой первый параграф, появляющийся при cell.text=''
            first = cell.paragraphs[0]
            if not first.text:
                first._element.getparent().remove(first._element)
            _set_cell_borders(cell)
            if col_widths_cm:
                cell.width = Cm(col_widths_cm[c_idx])
    return table


